#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn ids_are_unique_and_prefixed_by_category() {
        let mut seen = HashSet::new();
        for check in CHECKS {
            assert!(seen.insert(check.id), "duplicate id {}", check.id);
            let (prefix, name) = check.id.split_once('/').expect("id must be category/name");
            assert_eq!(prefix, check.category.slug(), "wrong prefix on {}", check.id);
            assert!(!name.is_empty());
            assert!(!check.title.is_empty() && !check.why.is_empty() && !check.fix.is_empty());
        }
    }

    #[test]
    fn every_category_has_checks() {
        for cat in Category::ALL {
            assert!(CHECKS.iter().any(|c| c.category == cat), "{cat:?} is empty");
        }
    }
}
