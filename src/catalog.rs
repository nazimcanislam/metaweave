//! The catalogue of every check: what it verifies, why it matters and how to fix it.
//! `metaweave list` and `metaweave explain` are generated from this table, and every
//! finding carries its `fix` text from here.

use crate::model::Category::{self, *};

pub struct Check {
    pub id: &'static str,
    pub category: Category,
    /// Needs extra HTTP requests beyond fetching the page itself.
    pub network: bool,
    pub title: &'static str,
    pub why: &'static str,
    pub fix: &'static str,
}

const fn c(
    id: &'static str,
    category: Category,
    network: bool,
    title: &'static str,
    why: &'static str,
    fix: &'static str,
) -> Check {
    Check { id, category, network, title, why, fix }
}

pub fn find(id: &str) -> Option<&'static Check> {
    CHECKS.iter().find(|c| c.id == id)
}

